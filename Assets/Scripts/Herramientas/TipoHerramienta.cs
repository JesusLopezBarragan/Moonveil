// Los tipos de herramienta que puede usar el jugador.
// Un enum es una lista de opciones con nombre: así no nos equivocamos escribiendo textos.
public enum TipoHerramienta
{
    Azada,      // convierte el césped en tierra arada
    Regadera,   // moja la tierra y hace que las zanahorias crezcan más rápido
    Pico,       // rompe rocas
    Hacha,      // rompe tocones, arbustos y corta la hierba
    Semillas    // planta zanahorias en la tierra arada
}
